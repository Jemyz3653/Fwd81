// Журнал ядра fwd81core.dll.
//
// Пишется БЕЗ библиотеки языка C — только через нативные функции ntdll.dll.
// Причина та же, что и у всего ядра: код исполняется в чужом процессе раньше,
// чем в нём заводится CRT. Любой сбой внутри логгера должен молча гаситься:
// журнал, роняющий разбираемый процесс, бесполезен (правило проекта).
//
// Уровни журнала совпадают с задумкой из docs (off/errors/resolutions/verbose),
// но само ядро на этапе M2 умеет только записывать событие; фильтрацию по уровню
// добавим, когда появятся сами события перехвата (M3).

#ifndef FWD81LOG_H
#define FWD81LOG_H

// Записать одно событие в журнал %LOCALAPPDATA%\Fwd81\logs\fwd81.log.
// level  — короткая ASCII-метка уровня ("info", "error", ...);
// event  — текст события (UTF-16), например L"ядро загружено в процесс".
// Логгер сам добавит метку времени (UTC), идентификатор процесса и путь к его
// образу. Ничего не возвращает и никогда не бросает исключений.
void Fwd81LogEvent(const char *level, const wchar_t *event);

#endif // FWD81LOG_H
