// Контрольный пример M3 (отказ №2): программа статически импортирует функцию из
// НЕсуществующей библиотеки fwd81_absent.dll. Загрузчик Windows при старте не
// найдёт эту DLL и не даст процессу дойти до main — точно так же, как реальная
// программа Windows 10 не запускается на 8.1 из-за отсутствующей api-ms-win-*.dll.
//
// ВАЖНО: импорт именно статический (через таблицу импорта), а не рантайм-вызов
// LoadLibrary. Это принципиально: перехват обязан ловить тот путь, каким
// загрузчик разрешает зависимости настоящих программ, а не удобный искусственный.
//
// Ожидаемое поведение:
//   * без Fwd81 — процесс падает при загрузке (STATUS_DLL_NOT_FOUND), main НЕ
//     достигается, строка ниже НЕ печатается;
//   * с Fwd81 (когда появятся перехваты) — ядро подставит библиотеку/заглушку,
//     процесс дойдёт до main и напечатает строку-маркер.

#include <stdio.h>

__declspec(dllimport) int Fwd81AbsentFunction(void);

int main(void)
{
    volatile int r = Fwd81AbsentFunction();  // ссылка удерживает статический импорт
    printf("SYNTHETIC-REACHED-MAIN absent_dll r=%d\n", r);
    fflush(stdout);
    return 0;
}
